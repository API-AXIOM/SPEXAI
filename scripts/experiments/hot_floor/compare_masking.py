"""Compare the hot-floor Fisher result with and without the Fe XXV mask.

The XRISM/Resolve Perseus analysis excludes 6.567-6.620 keV (observed frame),
which at Perseus's redshift covers the Fe XXV He-alpha resonance line w and
the intercombination line x while keeping y and the forbidden line z. That is
a RESONANCE SCATTERING cut: w is optically thick in the cluster core, so its
flux is redistributed and an optically-thin CIE model cannot reproduce it.

In THIS experiment both the injected truth and the fitted model are
optically-thin SPEX CIE, so resonance scattering is absent from both and the
mask corrects nothing -- it only removes channels. Whether to keep it is
therefore a real choice, and it turns out to matter a great deal: it moves the
binding parameter, the headline N*, and even the sign of Fe's bias. Both
configurations are reported in the paper for that reason.

Reads bias_{mode}_{masked_tag,unmasked_tag}.npz and emits a console table plus
LaTeX rows for the paper.

    KMP_DUPLICATE_LIB_OK=TRUE conda run -n spexai python \\
        scripts/experiments/hot_floor/compare_masking.py --mode single
    ... --mode dem --latex
"""
import argparse
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(REPO, "scripts", "inference"))
from spexai.config import RESULTS as _RESULTS_BASE                # noqa: E402

RESULTS = os.path.join(_RESULTS_BASE, "hot_floor")

# in-band count anchors: a single XRISM/Resolve region, and a deep stacked core
ANCHORS = (4e4, 1e6)


def load(mode, tag):
    p = os.path.join(RESULTS, f"bias_{mode}_{tag}.npz")
    if not os.path.exists(p):
        raise SystemExit(f"missing {p} -- run fisher_bias.py --mode {mode} "
                         f"--tag {tag} first")
    z = np.load(p, allow_pickle=True)
    if "arf" not in z.files:
        raise SystemExit(f"{os.path.basename(p)} records no ARF: it predates "
                         f"the response fix and is not valid.")
    return z


def nstar(z):
    """N* per parameter, with the count scale it was computed at."""
    b, s, nref = z["b_sys"], z["sigma_ref"], float(z["n_ref"])
    # b_sys == 0 exactly would mean no bias at all -> infinite crossover
    return np.where(b != 0, nref * (s / np.where(b != 0, np.abs(b), 1)) ** 2,
                    np.inf)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["single", "dem"], default="single")
    ap.add_argument("--masked_tag", default="arf")
    ap.add_argument("--unmasked_tag", default="nomask")
    ap.add_argument("--latex", action="store_true",
                    help="emit LaTeX table rows instead of the console table")
    args = ap.parse_args()

    m, u = load(args.mode, args.masked_tag), load(args.mode, args.unmasked_tag)
    names = list(map(str, m["names"]))
    if names != list(map(str, u["names"])):
        raise SystemExit("parameter lists differ between the two runs")
    nm, nu = nstar(m), nstar(u)

    if args.latex:
        print(f"% {args.mode}: Fe XXV masked vs unmasked, generated by "
              f"compare_masking.py")
        for i, p in enumerate(names):
            bias_m = " & ".join(f"{np.sqrt(N / nm[i]):.2f}" for N in ANCHORS)
            bias_u = " & ".join(f"{np.sqrt(N / nu[i]):.2f}" for N in ANCHORS)
            print(f"{p:<9} & ${nm[i]:.1e}$ & {bias_m} & ${nu[i]:.1e}$ & "
                  f"{bias_u} \\\\".replace("e+0", r"\times10^{").replace(
                      "$ &", "}$ &", 1))
        return

    print(f"=== {args.mode}: Fe XXV masked vs unmasked ===")
    print(f"masked   : {os.path.basename(str(m['rmf']))} + "
          f"{os.path.basename(str(m['arf']))}, cond(F)="
          f"{float(m['cond_F']):.2e}" if "cond_F" in m.files else "")
    print(f"{'param':>9} {'N* masked':>11} {'N* unmask':>11} {'ratio':>8} "
          f"{'sign':>5} | bias/sigma at 4e4, 1e6 (unmasked)")
    for i, p in enumerate(names):
        sign = "same" if np.sign(m["b_sys"][i]) == np.sign(u["b_sys"][i]) \
            else "FLIP"
        at = "  ".join(f"{np.sqrt(N / nu[i]):.3f}" for N in ANCHORS)
        print(f"{p:>9} {nm[i]:>11.2e} {nu[i]:>11.2e} {nu[i]/nm[i]:>8.2f} "
              f"{sign:>5} | {at}")

    for lab, arr in (("masked", nm), ("unmasked", nu)):
        j = int(np.argmin(arr))
        print(f"\nbinding parameter {lab:>8}: {names[j]} at N*={arr[j]:.2e} "
              f"-> {np.sqrt(ANCHORS[1]/arr[j]):.2f} sigma in a deep core")


if __name__ == "__main__":
    main()
